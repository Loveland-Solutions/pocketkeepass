#!/usr/bin/env python3
"""Regenerates app/src/main/res/raw/trusted_browsers.txt.

Usage:
    curl -sS -o /tmp/apps.json https://www.gstatic.com/gpm-passkeys-privileged-apps/apps.json
    python3 -I tools/trusted-browsers/update.py /tmp/apps.json app/src/main/res/raw/trusted_browsers.txt

The input is the list Google publishes of browsers that Android's Credential Manager lets act
for websites, with each one's signing certificate. PocketKeePass has no network access, so the
list is copied into the app at build time, by hand, with this script. Test tooling only: it
never ships.

Left out on purpose:
  - debug builds ("userdebug"), which are signed with keys anyone might have;
  - the entries that aren't browsers.
Review the diff before committing: a new line is a new app allowed to tell PocketKeePass which
website it's showing.
"""

import json
import sys

NOT_BROWSERS = {
    "com.google.android.gms",  # Google Play services
    "com.fido.fido2client",
    "com.oplus.credential",
    "com.citrix.Receiver",
}

HEADER = """\
# Browsers PocketKeePass trusts to say which website a login form belongs to, each with the
# SHA-256 of the certificate its real builds are signed with. One browser per line: its package
# name, then one or more certificates. Autofill matches entries to a website only for these; any
# other app is matched by its package name alone.
#
# Generated by tools/trusted-browsers/update.py from
# https://www.gstatic.com/gpm-passkeys-privileged-apps/apps.json. Don't edit by hand.
"""


def main(source: str, destination: str) -> None:
    with open(source, encoding="utf-8") as f:
        apps = json.load(f)["apps"]
    browsers: dict[str, list[str]] = {}
    for app in apps:
        info = app["info"]
        package = info["package_name"]
        if app["type"] != "android" or package in NOT_BROWSERS:
            continue
        for signature in info["signatures"]:
            if signature["build"] != "release":
                continue
            fingerprint = signature["cert_fingerprint_sha256"].replace(":", "").lower()
            if len(fingerprint) != 64 or any(c not in "0123456789abcdef" for c in fingerprint):
                raise SystemExit(f"{package}: not a SHA-256 fingerprint: {fingerprint!r}")
            certificates = browsers.setdefault(package, [])
            if fingerprint not in certificates:
                certificates.append(fingerprint)
    with open(destination, "w", encoding="utf-8") as f:
        f.write(HEADER)
        for package in sorted(browsers):
            f.write(" ".join([package, *browsers[package]]) + "\n")
    print(f"{len(browsers)} browsers")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
