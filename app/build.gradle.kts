// -------------------------------------------------------------------------------------------------
// The Rust engine (core/).
//
// Two things are built from it for every variant:
//   1. libpocketkeepass_core.so for each Android ABI, packaged into the APK;
//   2. the Kotlin bindings (package mn.lls.pocketkeepass.core), generated by UniFFI from the library.
//
// This calls cargo and the NDK's compiler directly. cargo-ndk would do the same, but its last
// release is over a year old, which the project's dependency rule doesn't allow.
// -------------------------------------------------------------------------------------------------

/** Finds cargo. Android Studio doesn't pass on the shell's PATH, so look in the usual places too. */
fun findCargo(): String {
    val home = System.getProperty("user.home")
    val candidates = listOfNotNull(
        System.getenv("CARGO"),
        System.getenv("CARGO_HOME")?.let { "$it/bin/cargo" },
        "$home/.cargo/bin/cargo",
        "/opt/homebrew/opt/rustup/bin/cargo",
        "/opt/homebrew/bin/cargo",
        "/usr/local/bin/cargo",
    ) + System.getenv("PATH").orEmpty().split(File.pathSeparator).map { "$it/cargo" }
    return candidates.firstOrNull { File(it).canExecute() }
        ?: throw GradleException("cargo wasn't found. Install Rust (https://rustup.rs) or set the CARGO environment variable.")
}

abstract class CargoTask : DefaultTask() {
    @get:Inject abstract val execOperations: ExecOperations

    @get:Internal abstract val crateDir: DirectoryProperty

    /** Everything the build result depends on, so Gradle can skip cargo when nothing changed. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    @get:Input abstract val cargo: Property<String>

    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @get:Internal
    protected val targetDir: File get() = crateDir.get().asFile.resolve("target")

    protected fun run(command: List<String>, env: Map<String, String> = emptyMap()) {
        execOperations.exec {
            workingDir = crateDir.get().asFile
            commandLine(command)
            environment(env)
            // cargo needs rustc, which lives next to it.
            val path = System.getenv("PATH").orEmpty()
            environment("PATH", File(cargo.get()).parent + File.pathSeparator + path)
        }
    }

    protected fun cargoBuild(vararg extra: String, env: Map<String, String> = emptyMap()) {
        // --release always: key derivation is far too slow in an unoptimized build.
        run(listOf(cargo.get(), "build", "--release", "--locked", "--target-dir", targetDir.path) + extra, env)
    }
}

/** Cross-compiles the engine for every ABI into `<outputDir>/<abi>/libpocketkeepass_core.so`. */
abstract class BuildRustForAndroid : CargoTask() {
    @get:Internal abstract val ndkDir: DirectoryProperty

    @get:Input abstract val ndkVersion: Property<String>

    @get:Input abstract val minSdk: Property<Int>

    /** Android ABI → Rust target. */
    @get:Input abstract val targets: MapProperty<String, String>

    @TaskAction
    fun build() {
        val os = System.getProperty("os.name").lowercase()
        val host = when {
            os.contains("mac") -> "darwin-x86_64" // the NDK's macOS tools are universal binaries
            os.contains("windows") -> "windows-x86_64"
            else -> "linux-x86_64"
        }
        val tools = ndkDir.get().asFile.resolve("toolchains/llvm/prebuilt/$host/bin")
        val suffix = if (os.contains("windows")) ".cmd" else ""
        outputDir.get().asFile.deleteRecursively()

        // Rust keeps source paths in the library (for panic messages), and they start with the
        // home folder, whose name is the developer's account name. Shipped to everyone who
        // installs the app, so they're rewritten to neutral ones. (Also a step towards builds
        // that come out the same on any computer.)
        val home = System.getProperty("user.home")
        // rustc applies the last one that matches, so the home folder, the broadest, goes first.
        val remaps = listOf(
            home to "~",
            (System.getenv("CARGO_HOME") ?: "$home/.cargo") to "/cargo",
            (System.getenv("RUSTUP_HOME") ?: "$home/.rustup") to "/rustup",
            crateDir.get().asFile.path to "/src",
        )
        // One flag per entry, separated by 0x1F: paths with spaces stay whole.
        val rustflags = remaps.joinToString("\u001f") { (from, to) -> "--remap-path-prefix=$from=$to" }

        for ((abi, target) in targets.get()) {
            // The NDK names its 32-bit ARM compiler "armv7a", where Rust says "armv7".
            val clang = target.replace("armv7-", "armv7a-") + minSdk.get() + "-clang" + suffix
            val linker = tools.resolve(clang).path
            val envName = target.replace('-', '_')
            cargoBuild(
                "--target", target,
                env = mapOf(
                    "CARGO_ENCODED_RUSTFLAGS" to rustflags,
                    "CARGO_TARGET_${envName.uppercase()}_LINKER" to linker,
                    // Only used if a dependency ever compiles C code. None does today.
                    "CC_$envName" to linker,
                    "AR_$envName" to tools.resolve("llvm-ar").path,
                ),
            )
            val library = targetDir.resolve("$target/release/libpocketkeepass_core.so")
            library.copyTo(outputDir.get().asFile.resolve("$abi/libpocketkeepass_core.so"))
        }
    }
}

/** Builds the engine for this computer and has UniFFI generate the Kotlin bindings from it. */
abstract class GenerateKotlinBindings : CargoTask() {
    @TaskAction
    fun generate() {
        cargoBuild("--features", "bindgen")
        val os = System.getProperty("os.name").lowercase()
        val library = when {
            os.contains("mac") -> "libpocketkeepass_core.dylib"
            os.contains("windows") -> "pocketkeepass_core.dll"
            else -> "libpocketkeepass_core.so"
        }
        val release = targetDir.resolve("release")
        outputDir.get().asFile.deleteRecursively()
        run(
            listOf(
                release.resolve("uniffi-bindgen").path, "generate",
                "--language", "kotlin",
                "--no-format",
                "--out-dir", outputDir.get().asFile.path,
                release.resolve(library).path,
            ),
        )
    }
}

val coreDir = rootProject.layout.projectDirectory.dir("core")

fun CargoTask.configureCargo() {
    crateDir.set(coreDir)
    cargo.set(provider { findCargo() })
    sources.from(coreDir.dir("src"), coreDir.file("Cargo.toml"), coreDir.file("Cargo.lock"), coreDir.file("uniffi.toml"))
}

androidComponents {
    onVariants { variant ->
        val name = variant.name.replaceFirstChar { it.uppercase() }

        val buildRust = tasks.register<BuildRustForAndroid>("buildRust$name") {
            description = "Builds the Rust engine for Android."
            configureCargo()
            ndkDir.set(androidComponents.sdkComponents.ndkDirectory)
            ndkVersion.set(android.ndkVersion)
            minSdk.set(android.defaultConfig.minSdk)
            targets.set(rustTargets)
        }
        variant.sources.jniLibs?.addGeneratedSourceDirectory(buildRust, BuildRustForAndroid::outputDir)

        val bindings = tasks.register<GenerateKotlinBindings>("generateRustBindings$name") {
            description = "Generates the Kotlin bindings for the Rust engine."
            configureCargo()
        }
        variant.sources.kotlin?.addGeneratedSourceDirectory(bindings, GenerateKotlinBindings::outputDir)
    }
}
